create schema if not exists cron;
create table if not exists cron.job(jobid bigint generated by default as identity primary key,jobname text unique,schedule text,command text,username text default current_user,active boolean default true);
create or replace function cron.schedule(text,text,text) returns bigint language plpgsql as $$
declare v_id bigint;
begin
  insert into cron.job(jobname,schedule,command) values($1,$2,$3)
  on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command returning jobid into v_id;
  return v_id;
end $$;
create or replace function cron.alter_job(job_id bigint,active boolean default null) returns void language sql as $$
  update cron.job set active=$2 where jobid=$1;
$$;
